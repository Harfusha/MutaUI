def _build_help_index(
    settings_help: tuple[SettingHelp, ...], defaults: Mapping[str, Any]
) -> dict[str, SettingHelp]:
    help_by_key = {item.key: item for item in settings_help}
    if len(help_by_key) != len(settings_help):
        raise RuntimeError("Settings help registry contains duplicate keys.")
    if any(item.default != defaults.get(item.key) for item in settings_help):
        raise RuntimeError("Settings help defaults do not match settings validation defaults.")
    return help_by_key


HELP_BY_KEY = _build_help_index(SETTINGS_HELP, DEFAULT_SETTINGS)


def setting_tooltip(key: str, language: str = "en") -> str:
    item = HELP_BY_KEY[key]
    is_czech = language == "cs"
    description = item.description_cs if is_czech else item.description_en
    recommended = item.recommended_cs if is_czech else item.recommended_en
    validation = item.validation_cs if is_czech else item.validation_en
    scope = item.scope_cs if is_czech else item.scope_en
    recommendation_label = "Doporučeno" if is_czech else "Recommended"
    validation_label = "Platné hodnoty" if is_czech else "Valid values"
    effect_label = "Vliv" if is_czech else "Effect"
    return (
        f"{description}\n{recommendation_label}: {recommended}\n"
        f"{validation_label}: {validation}\n{effect_label}: {scope}"
    )


def render_reference() -> str:
    lines = [
        "# Settings reference (generated)",
        "",
        "Generated from `mutaui.ui.settings_registry`; edit registry metadata instead of this file.",
        "Application settings below do not directly modify Mutagen configuration unless the mapping says so.",
        "",
    ]
    for item in SETTINGS_HELP:
        lines.extend(
            [
                f"## {item.title_en} / {item.title_cs}",
                "",
                f"- Key: `{item.key}`",
                f"- Group: {item.group}",
                f"- Default: `{item.default}`",
                f"- Platforms: {', '.join(item.platforms)}",
                f"- Valid values: {item.validation_en} / {item.validation_cs}",
                f"- Recommended: {item.recommended_en} / {item.recommended_cs}",
                f"- Effect: {item.scope_en} / {item.scope_cs}",
                f"- Mutagen mapping: {item.native_mapping}",
                "",
                f"{item.description_en} / {item.description_cs}",
            ]
        )
        if item.documentation_url:
            lines.append(f"[Mutagen documentation]({item.documentation_url})")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_reference(path: str | Path) -> None:
    Path(path).write_text(render_reference(), encoding="utf-8")
