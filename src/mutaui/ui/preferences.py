def resolve_theme(theme: str, *, system_is_light: bool) -> str:
    if theme == "system":
        return "light" if system_is_light else "dark"
    return theme if theme in {"light", "dark"} else "dark"


def native_shortcut_text(text: str) -> str:
    """Render portable Ctrl shortcuts with the host platform's native labels."""
    return _SHORTCUT_PATTERN.sub(
        lambda match: QKeySequence(match.group()).toString(QKeySequence.SequenceFormat.NativeText),
        text,
    )


def translate(key: str, language: str) -> str:
    entry = _CATALOG.get(key)
    if entry is None:
        return key
    return entry.get(language, entry["en"])


def translate_text(text: str, language: str) -> str:
    if language == "cs":
        translated = _TEXT_CATALOG.get(
            text,
            _TOOLTIP_CATALOG.get(
                text,
                _PLACEHOLDER_CATALOG.get(
                    text,
                    _TITLE_CATALOG.get(text, _DIALOG_CATALOG.get(text, text)),
                ),
            ),
        )
    else:
        translated = text
    return native_shortcut_text(translated)


def translate_route(route_id: str, field: str, language: str, fallback: str) -> str:
    if language == "cs":
        entry = _ROUTE_CATALOG.get(route_id, {}).get(field)
        fallback = entry[1] if entry else fallback
    return native_shortcut_text(fallback)


def set_active_language(language: str) -> str:
    global _ACTIVE_LANGUAGE
    _ACTIVE_LANGUAGE = language if language in LANGUAGES else "en"
    return _ACTIVE_LANGUAGE


def active_language() -> str:
    return _ACTIVE_LANGUAGE


def theme_stylesheet(stylesheet: str, theme: str) -> str:
    if theme != "light":
        return stylesheet
    for dark, light in _LIGHT_COLORS.items():
        stylesheet = stylesheet.replace(dark, light)
    return stylesheet
